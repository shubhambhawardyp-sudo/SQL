-- Create Audit table

CREATE TABLE Library_Audit (
    Audit_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    Book_ID NUMBER,
    Book_Name VARCHAR2(100),
    Author VARCHAR2(100),
    Price NUMBER,
    Operation VARCHAR2(20),
    Audit_Date DATE
);


-- AFTER UPDATE ROW-LEVEL TRIGGER

CREATE OR REPLACE TRIGGER trg_library_update
AFTER UPDATE ON Library
FOR EACH ROW
BEGIN
    INSERT INTO Library_Audit
    (
        Book_ID,
        Book_Name,
        Author,
        Price,
        Operation,
        Audit_Date
    )
    VALUES
    (
        :OLD.Book_ID,
        :OLD.Book_Name,
        :OLD.Author,
        :OLD.Price,
        'UPDATE',
        SYSDATE
    );
END;
/


-- AFTER DELETE ROW-LEVEL TRIGGER

CREATE OR REPLACE TRIGGER trg_library_delete
AFTER DELETE ON Library
FOR EACH ROW
BEGIN
    INSERT INTO Library_Audit
    (
        Book_ID,
        Book_Name,
        Author,
        Price,
        Operation,
        Audit_Date
    )
    VALUES
    (
        :OLD.Book_ID,
        :OLD.Book_Name,
        :OLD.Author,
        :OLD.Price,
        'DELETE',
        SYSDATE
    );
END;
/


-- STATEMENT-LEVEL TRIGGER

CREATE OR REPLACE TRIGGER trg_library_statement
AFTER UPDATE ON Library
BEGIN
    DBMS_OUTPUT.PUT_LINE('Library table was updated.');
END;
